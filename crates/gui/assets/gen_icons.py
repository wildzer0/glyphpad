#!/usr/bin/env python3
"""Regenerates `src/icons.rs` and `assets/Phosphor-subset.ttf`.

Phosphor Icons (MIT) ship as one 480 KB font; the window uses ~90 glyphs. To add an icon, put
its name (as in `codepoints.rs` of the `egui-phosphor` crate, e.g. `ARROW_UP`) in NAMES below
and run, from the repository root:

    pip install fonttools
    python3 crates/gui/assets/gen_icons.py /path/to/egui-phosphor-0.14.0

(the crate is only used as a convenient copy of the font and its codepoint names; GlyphPad does
not depend on it).
"""
import re
import subprocess
import sys

NAMES = """HAND_TAP SCRIBBLE_LOOP GEAR_SIX PULSE PLUS TRASH COPY MAGNIFYING_GLASS X CHECK CHECK_CIRCLE
WARNING WARNING_CIRCLE INFO DOTS_THREE DOTS_SIX_VERTICAL CARET_RIGHT CARET_DOWN CARET_UP PENCIL_SIMPLE
PLAY PAUSE ARROW_COUNTER_CLOCKWISE ARROW_CLOCKWISE SUN MOON CIRCLE_HALF FOLDER_OPEN ARROW_RIGHT
ARROW_LEFT ARROW_UP ARROW_DOWN STOP RECORD FLASK POWER KEYBOARD MONITOR EYE REPEAT PROHIBIT LIGHTNING
CURSOR_CLICK HAND_SWIPE_RIGHT ARROWS_IN_SIMPLE ARROWS_OUT_SIMPLE BOUNDING_BOX ARROW_ELBOW_DOWN_RIGHT
TERMINAL_WINDOW BELL SPEAKER_HIGH LOCK_SIMPLE SQUARE MINUS STACK CLOCK APP_WINDOW CLOUD_CHECK
FLOPPY_DISK DOWNLOAD_SIMPLE HAND_PALM CIRCLE_NOTCH ARROWS_CLOCKWISE LIST_BULLETS TIMER SPARKLE FUNNEL
ARROW_SQUARE_OUT SKIP_FORWARD PLAY_PAUSE ARROW_UP_LEFT ARROW_UP_RIGHT ARROW_DOWN_LEFT ARROW_DOWN_RIGHT
HAND_FIST ARROWS_LEFT_RIGHT TEXT_AA CAMERA SQUARES_FOUR USER_SWITCH USERS EXPORT CHART_BAR TRANSLATE
LIST_CHECKS UPLOAD_SIMPLE PACKAGE MOUSE_SIMPLE FINGERPRINT QUEUE CLOCK_COUNTER_CLOCKWISE
SLIDERS_HORIZONTAL SELECTION_PLUS""".split()

crate = sys.argv[1]
codepoints = dict(
    re.findall(
        r'pub const (\w+): &str = "\\u\{([0-9A-F]+)\}";',
        open(crate + "/src/variants/codepoints.rs").read(),
    )
)
lines = [
    "//! Phosphor icons (MIT, https://phosphoricons.com), subset to the glyphs the window uses.",
    "//! Generated by `assets/gen_icons.py`; do not edit by hand.",
    "",
    "#![allow(dead_code)]",
    "",
]
unicodes = []
for name in NAMES:
    if name not in codepoints:
        sys.exit(f"unknown icon {name}")
    lines.append(f'pub const {name}: &str = "\\u{{{codepoints[name]}}}";')
    unicodes.append("U+" + codepoints[name])
open("crates/gui/src/icons.rs", "w").write("\n".join(lines) + "\n")
subprocess.check_call(
    [
        "pyftsubset",
        crate + "/res/Phosphor.ttf",
        "--unicodes=" + ",".join(unicodes),
        "--output-file=crates/gui/assets/Phosphor-subset.ttf",
        "--no-hinting",
        "--layout-features=",
    ]
)
